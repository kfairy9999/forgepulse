from __future__ import annotations

from forgepulse.infer import extract_filenames, infer_ai_assisted, infer_has_tests, is_test_path


def test_test_path_patterns() -> None:
    assert is_test_path("tests/test_engine.py")
    assert is_test_path("src/engine_test.go")
    assert is_test_path("app/CheckoutForm.test.tsx")
    assert is_test_path("pkg/auth/chain_spec.ts") is False
    assert is_test_path("app/checkout.spec.ts")
    assert is_test_path("src/settlement/engine.py") is False


def test_infer_has_tests_unknown_without_paths() -> None:
    assert infer_has_tests(None) == (None, "unknown")
    assert infer_has_tests([]) == (None, "unknown")


def test_infer_has_tests_from_paths() -> None:
    assert infer_has_tests(["src/engine.py", "tests/test_engine.py"]) == (True, "inferred")
    assert infer_has_tests(["src/engine.py"]) == (False, "inferred")


def test_extract_filenames_from_several_shapes() -> None:
    payload = {
        "files": [{"filename": "src/a.py"}, "tests/test_a.py"],
        "commits": [{"added": ["extra.py"]}],
    }
    assert extract_filenames(payload) == ["src/a.py", "tests/test_a.py"]
    assert extract_filenames({"pull_request": {"files": [{"path": "pkg/auth/chain.go"}]}}) == [
        "pkg/auth/chain.go"
    ]
    assert extract_filenames({"commits": [{"modified": ["foo.py"], "removed": ["old.py"]}]}) == [
        "foo.py",
        "old.py",
    ]
    assert extract_filenames({"pull_request": {"changed_files": 3}}) is None


def test_infer_ai_assisted_from_hints() -> None:
    assert infer_ai_assisted({"title": "Generated by Copilot"}, None) is True
    assert infer_ai_assisted({"labels": [{"name": "ai-assisted"}]}, None) is True
    assert infer_ai_assisted({"user": {"login": "imgbot[bot]"}}, None) is True
    assert infer_ai_assisted({"title": "Fix rounding"}, None) is None
    assert infer_ai_assisted({"title": "Generated by Copilot"}, False) is False
