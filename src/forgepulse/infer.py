"""Infer test presence, protected paths, and AI assistance from payloads."""

from __future__ import annotations

import re
from typing import Any

from forgepulse.models import TestEvidence

# Paths that usually mean automated tests traveled with the change.
_TEST_PATH = re.compile(
    r"(?:^|/)(?:tests?|spec|__tests__|e2e|cypress|testdata)(?:/|$)"
    r"|(?:^|/)test_[^/]+$"
    r"|[^/]+_test\.[^/]+$"
    r"|[^/]+\.(?:tests?|spec)\.[^/]+$",
    re.IGNORECASE,
)

_AI_HINT = re.compile(
    r"\b(?:copilot|chatgpt|openai|claude|gemini|generated by|ai-assisted|"
    r"cursor agent|aider|codex)\b",
    re.IGNORECASE,
)
_AI_LABELS = {
    "ai",
    "ai-generated",
    "ai-assisted",
    "copilot",
    "generated",
}


def is_test_path(path: str) -> bool:
    normalized = path.replace("\\", "/").strip()
    return bool(normalized and _TEST_PATH.search(normalized))


def infer_has_tests(paths: list[str] | None) -> tuple[bool | None, TestEvidence]:
    """Return (has_tests, source).

    ``source`` is ``inferred`` when file paths were available, otherwise
    ``unknown``. Callers that already know the answer should mark it
    ``explicit`` themselves.
    """
    if not paths:
        return None, "unknown"
    return any(is_test_path(path) for path in paths), "inferred"


def protected_hits(paths: list[str], prefixes: list[str]) -> list[str]:
    hits: list[str] = []
    seen: set[str] = set()
    for path in paths:
        normalized = path.replace("\\", "/").lstrip("./")
        for prefix in prefixes:
            if normalized.startswith(prefix) and path not in seen:
                hits.append(path)
                seen.add(path)
                break
    return hits


def extract_filenames(payload: dict[str, Any]) -> list[str] | None:
    """Collect changed paths from a webhook-like payload, if present.

    GitHub's native ``pull_request`` event does not include file names. When
    they are missing this returns ``None`` so callers can flag the gap instead
    of pretending ``has_tests=False``.
    """
    names = _from_file_list(payload.get("files"))
    pull_request = payload.get("pull_request")
    if not names and isinstance(pull_request, dict):
        names = _from_file_list(pull_request.get("files"))
    if not names:
        collected: list[str] = []
        commits = payload.get("commits")
        if isinstance(commits, list):
            for commit in commits:
                if not isinstance(commit, dict):
                    continue
                for key in ("added", "modified", "removed"):
                    collected.extend(_string_list(commit.get(key)))
        names = collected
    return names or None


def infer_ai_assisted(payload: dict[str, Any], explicit: bool | None) -> bool | None:
    if explicit is not None:
        return explicit
    pull_request = payload.get("pull_request")
    if not isinstance(pull_request, dict):
        pull_request = payload
    title = str(pull_request.get("title") or "")
    body = str(pull_request.get("body") or "")
    if _AI_HINT.search(title) or _AI_HINT.search(body):
        return True
    for label in _label_names(pull_request.get("labels")):
        if label.lower() in _AI_LABELS or _AI_HINT.search(label):
            return True
    user = pull_request.get("user")
    if isinstance(user, dict):
        login = str(user.get("login") or "")
        if login.endswith("[bot]") or user.get("type") == "Bot":
            return True
    return None


def _from_file_list(files: object) -> list[str]:
    if not isinstance(files, list):
        return []
    names: list[str] = []
    for item in files:
        if isinstance(item, str) and item.strip():
            names.append(item.strip())
        elif isinstance(item, dict):
            for key in ("filename", "path", "name"):
                value = item.get(key)
                if isinstance(value, str) and value.strip():
                    names.append(value.strip())
                    break
    return names


def _string_list(value: object) -> list[str]:
    if not isinstance(value, list):
        return []
    return [item.strip() for item in value if isinstance(item, str) and item.strip()]


def _label_names(labels: object) -> list[str]:
    if not isinstance(labels, list):
        return []
    names: list[str] = []
    for label in labels:
        if isinstance(label, str):
            names.append(label)
        elif isinstance(label, dict):
            name = label.get("name")
            if isinstance(name, str):
                names.append(name)
    return names
